"""Create/populate the Fiddler Project -> Application -> Dataset chain
from a list of parsed promptfoo red-team test cases."""

from __future__ import annotations

from datetime import UTC, datetime

from fiddler_evals import Application, Dataset, Project, init
from fiddler_evals.pydantic_models.dataset import NewDatasetItem

from .config import FiddlerSettings
from .promptfoo_parser import RedteamTestCase


def connect(settings: FiddlerSettings) -> Application:
    init(url=settings.url, token=settings.api_key)
    project = Project.get_or_create(name=settings.project)
    application = Application.get_or_create(
        name=settings.application, project_id=project.id
    )
    return application


def build_dataset(
    application: Application,
    cases: list[RedteamTestCase],
    name_prefix: str = "promptfoo-redteam",
) -> Dataset:
    timestamp = datetime.now(UTC).strftime("%Y%m%d-%H%M%S")
    dataset = Dataset.create(
        name=f"{name_prefix}-{timestamp}",
        application_id=application.id,
        description=(
            f"{len(cases)} adversarial prompts generated by promptfoo redteam, "
            "scored against Fiddler Guardrails for safety/PII detection."
        ),
    )

    items = [
        NewDatasetItem(
            inputs={"prompt": case.prompt},
            expected_outputs={
                "should_flag": case.should_flag,
                "category": case.category,
            },
            metadata={
                "plugin_id": case.plugin_id,
                "category": case.category,
                "severity": case.severity,
                "metric": case.metric,
                "strategy_id": case.strategy_id,
                "source": "promptfoo",
            },
        )
        for case in cases
    ]
    dataset.insert(items)
    return dataset
